-- ====================================================================
-- cdr: cd to git repository root
-- ====================================================================
vim.cmd("cabbrev cdr execute 'cd' system('git rev-parse --show-toplevel')")

-- ====================================================================
-- cdh: cd to current file's directory
-- ====================================================================
vim.cmd("cabbrev cdh cd %:h")

-- ====================================================================
-- vfind: fuzzy find file in vertical split
-- ====================================================================
vim.cmd("cabbrev vfind vert sfind")

-- ====================================================================
-- trn: toggle relative number
-- ====================================================================
vim.cmd("cabbrev trn set relativenumber!")
